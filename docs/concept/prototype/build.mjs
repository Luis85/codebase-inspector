import {readFile,writeFile,mkdir} from 'node:fs/promises';
import {fileURLToPath} from 'node:url';
import {dirname,join} from 'node:path';
import {createHash} from 'node:crypto';
const root=dirname(fileURLToPath(import.meta.url));
const read=p=>readFile(join(root,p),'utf8');
const vendor=await read('vendor/three-r140.min.js');
const blobHash=createHash('sha1').update(`blob ${Buffer.byteLength(vendor)}\0`).update(vendor).digest('hex');
if(blobHash!=='c948a8be35302c3bd446e79be99433ed4e1ef89e')throw new Error('Three.js vendor integrity check failed.');
const license=await read('vendor/THREE-LICENSE.txt');
const runtime='/* Bundled Three.js r140. '+license.replace(/\*\//g,'* /')+' */\n'+vendor+'\n;\n'+await read('src/model.js')+'\n;\n'+await read('src/viewer.js');
const app=await read('src/fixture.js')+'\n;\n'+await read('src/app.js');
const css=await read('src/styles.css'),template=await read('src/template.html'),sprite=await read('assets/icons.svg');
await writeFile(join(root,'viewer.bundle.js'),runtime);await writeFile(join(root,'demo.bundle.js'),app);await writeFile(join(root,'styles.css'),css);
const common=template.replace('<!-- ICONS -->',sprite);
const index=common.replace('<!-- STYLE -->','<link rel="stylesheet" href="styles.css">').replace('<!-- SCRIPTS -->','<script src="viewer.bundle.js"></script>\n<script src="demo.bundle.js"></script>');
const single=common.replace('<!-- STYLE -->',`<style>${css}</style>`).replace('<!-- SCRIPTS -->',`<script>${runtime.replace(/<\/script/gi,'<\\/script')}</script>\n<script>${app.replace(/<\/script/gi,'<\\/script')}</script>`);
await writeFile(join(root,'index.html'),index);await writeFile(join(root,'standalone.html'),single);
console.log(`Built index.html + bundled viewer and standalone.html (${Buffer.byteLength(single).toLocaleString()} bytes). No dependency installation needed.`);
